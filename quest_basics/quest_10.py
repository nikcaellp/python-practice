import math 
an = int(input("Digite um angulo"))
seno = math.sin(math.radians(an))
print(f"o angulo de {an} tem o seno de {seno}")
cosseno = math.cos(math.radians(an))
print(f"o angulo de {an} tem o seno de {cosseno}")
tang = math.tan(math.radians(an))
print(f"o angulo de {an} tem o seno de {tang}")

